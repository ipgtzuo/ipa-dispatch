import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case zh
    case en

    var id: String { rawValue }
    var label: String { self == .zh ? "中文" : "English" }
    var shortLabel: String { self == .zh ? "中" : "EN" }
    var locale: Locale { Locale(identifier: self == .zh ? "zh_Hans" : "en") }

    static var systemDefault: AppLanguage {
        let preferred = Locale.preferredLanguages.first ?? "en"
        return preferred.lowercased().hasPrefix("zh") ? .zh : .en
    }
}

struct LocalizedMessage: Equatable {
    let key: String
    let args: [String]

    init(_ key: String, _ args: String...) {
        self.key = key
        self.args = args
    }

    init(_ key: String, args: [String]) {
        self.key = key
        self.args = args
    }
}

