        let table = language == .zh ? zh : en
        let format = table[message.key] ?? en[message.key] ?? message.key
        guard !message.args.isEmpty else { return format }
        return String(format: format, arguments: message.args.map { $0 as CVarArg })
    }

    static func text(_ language: AppLanguage, _ key: String, _ args: String...) -> String {
        text(language, LocalizedMessage(key, args: args))
    }

    static func text(_ language: AppLanguage, _ key: String, args: [String]) -> String {
        text(language, LocalizedMessage(key, args: args))
